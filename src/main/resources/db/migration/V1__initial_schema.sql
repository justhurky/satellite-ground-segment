create table app_user (
    id uuid primary key,
    username varchar(64) not null unique,
    password_hash varchar(100) not null,
    enabled boolean not null,
    created_at timestamp with time zone not null
);

create table app_user_role (
    user_id uuid not null references app_user (id) on delete cascade,
    role varchar(32) not null,
    primary key (user_id, role)
);

create table spacecraft (
    id uuid primary key,
    name varchar(64) not null unique,
    norad_id integer not null unique,
    mission_phase varchar(32) not null,
    telemetry_key_sealed bytea not null,
    command_public_key bytea not null,
    registered_at timestamp with time zone not null,
    constraint ck_spacecraft_mission_phase check (
        mission_phase in ('COMMISSIONING', 'NOMINAL', 'SAFE_MODE', 'DECOMMISSIONED'))
);

create table parameter_definition (
    id bigint generated by default as identity primary key,
    spacecraft_id uuid not null references spacecraft (id),
    parameter_slot integer not null,
    name varchar(64) not null,
    unit varchar(16) not null,
    red_low double precision,
    yellow_low double precision,
    yellow_high double precision,
    red_high double precision,
    constraint uq_parameter_definition_slot unique (spacecraft_id, parameter_slot),
    constraint uq_parameter_definition_name unique (spacecraft_id, name),
    constraint ck_parameter_definition_slot check (parameter_slot between 0 and 255)
);

create table ground_station (
    id uuid primary key,
    code varchar(16) not null unique,
    name varchar(64) not null,
    latitude_degrees double precision not null,
    longitude_degrees double precision not null,
    altitude_metres double precision not null,
    active boolean not null,
    constraint ck_ground_station_latitude check (latitude_degrees between -90 and 90),
    constraint ck_ground_station_longitude check (longitude_degrees between -180 and 180)
);

create table contact_window (
    id uuid primary key,
    spacecraft_id uuid not null references spacecraft (id),
    ground_station_id uuid not null references ground_station (id),
    starts_at timestamp with time zone not null,
    ends_at timestamp with time zone not null,
    uplink_budget_bytes integer not null,
    uplinked_bytes integer not null,
    version bigint not null,
    constraint ck_contact_window_bounds check (ends_at > starts_at),
    constraint ck_contact_window_budget check (uplinked_bytes >= 0 and uplinked_bytes <= uplink_budget_bytes)
);

create table telemetry_frame (
    id bigint generated by default as identity primary key,
    spacecraft_id uuid not null references spacecraft (id),
    ground_station_id uuid not null references ground_station (id),
    apid integer not null,
    sequence_count integer not null,
    sequence_flags integer not null,
    generated_at timestamp with time zone not null,
    received_at timestamp with time zone not null,
    payload_length integer not null,
    payload_sealed bytea not null,
    constraint ck_telemetry_frame_apid check (apid between 0 and 2047),
    constraint ck_telemetry_frame_sequence check (sequence_count between 0 and 16383)
);

create table telemetry_sample (
    id bigint generated by default as identity primary key,
    frame_id bigint not null references telemetry_frame (id) on delete cascade,
    parameter_slot integer not null,
    parameter_name varchar(64) not null,
    observed_value double precision not null,
    unit varchar(16) not null,
    mapped boolean not null,
    generated_at timestamp with time zone not null
);

create table sequence_state (
    id bigint generated by default as identity primary key,
    spacecraft_id uuid not null references spacecraft (id),
    apid integer not null,
    last_sequence integer not null,
    seen_mask bigint not null,
    updated_at timestamp with time zone not null,
    version bigint not null,
    constraint uq_sequence_state_stream unique (spacecraft_id, apid)
);

create table alert (
    id uuid primary key,
    spacecraft_id uuid not null references spacecraft (id),
    frame_id bigint not null,
    parameter_name varchar(64) not null,
    observed_value double precision not null,
    severity varchar(16) not null,
    limit_kind varchar(16) not null,
    limit_value double precision not null,
    raised_at timestamp with time zone not null,
    acknowledged boolean not null,
    acknowledged_by varchar(64),
    acknowledged_at timestamp with time zone,
    constraint ck_alert_severity check (severity in ('YELLOW', 'RED')),
    constraint ck_alert_limit_kind check (
        limit_kind in ('RED_LOW', 'YELLOW_LOW', 'YELLOW_HIGH', 'RED_HIGH'))
);

create table telecommand (
    id uuid primary key,
    spacecraft_id uuid not null references spacecraft (id),
    opcode varchar(64) not null,
    criticality varchar(16) not null,
    priority integer not null,
    state varchar(16) not null,
    canonical_parameters varchar(1024) not null,
    nonce varchar(64) not null,
    requested_at timestamp with time zone not null,
    submitted_at timestamp with time zone not null,
    execute_after timestamp with time zone,
    signature bytea not null,
    payload_digest varchar(64) not null,
    payload_bytes integer not null,
    requested_by varchar(64) not null,
    contact_window_id uuid,
    scheduled_at timestamp with time zone,
    uplinked_at timestamp with time zone,
    completed_at timestamp with time zone,
    result_code integer,
    outcome_detail varchar(256),
    version bigint not null,
    constraint uq_telecommand_nonce unique (spacecraft_id, nonce),
    constraint ck_telecommand_criticality check (criticality in ('ROUTINE', 'SENSITIVE', 'CRITICAL')),
    constraint ck_telecommand_state check (state in (
        'RECEIVED', 'VALIDATED', 'SCHEDULED', 'UPLINKED', 'ACKNOWLEDGED', 'FAILED', 'REJECTED', 'CANCELLED'))
);

create table audit_event (
    id bigint generated by default as identity primary key,
    event_sequence bigint not null unique,
    occurred_at timestamp with time zone not null,
    actor varchar(64) not null,
    action varchar(48) not null,
    resource_type varchar(48) not null,
    resource_id varchar(64),
    details varchar(2048) not null,
    previous_hash varchar(64) not null,
    hash varchar(64) not null
);
